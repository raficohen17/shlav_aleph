#!/usr/bin/env python3
"""Bundle tests/test_*.html into quiz/tests-data.js for the online quiz.

The quiz parses each test's HTML in the browser, so this script only extracts
the <title> and <body> of every test. Bundling into a .js file (instead of
fetching the HTML at runtime) lets quiz.html work from file:// with no server.

Usage: python3 scripts/build_quiz_data.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
TESTS_DIR = ROOT / "tests"
OUT = ROOT / "quiz" / "tests-data.js"


def test_number(path: pathlib.Path) -> int:
    match = re.fullmatch(r"test_(\d+)\.html", path.name)
    return int(match.group(1)) if match else -1


def extract(html: str) -> dict:
    title = re.search(r"<title>(.*?)</title>", html, re.S)
    body = re.search(r"<body[^>]*>(.*)</body>", html, re.S)
    if not body:
        raise ValueError("no <body> found")
    return {"title": title.group(1).strip() if title else "", "html": body.group(1).strip()}


def count_questions(html: str) -> int:
    main = html.split('class="answers"')[0]
    return len(re.findall(r'<div[^>]*class="q[ "]', main))


def count_key_rows(html: str) -> int:
    parts = html.split('class="answers"')
    return len(re.findall(r"<tr><td>", parts[1])) if len(parts) > 1 else 0


def build() -> list:
    tests = []
    for path in sorted(TESTS_DIR.glob("test_*.html"), key=test_number):
        num = test_number(path)
        if num < 1:
            continue
        html = path.read_text(encoding="utf-8")
        q, rows = count_questions(html), count_key_rows(html)
        if q != rows:
            raise SystemExit(f"{path.name}: {q} questions but {rows} answer-key rows")
        item = extract(html)
        item.update({"id": num, "pdf": f"pdf/test_{num}.pdf", "questions": q})
        tests.append(item)
    return tests


def main() -> None:
    tests = build()
    payload = json.dumps(tests, ensure_ascii=False).replace("</", "<\\/")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/build_quiz_data.py – do not edit by hand.\n"
        f"window.SHLAV_TESTS = {payload};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}: " + ", ".join(f"test {t['id']} ({t['questions']} q)" for t in tests))


if __name__ == "__main__":
    main()
