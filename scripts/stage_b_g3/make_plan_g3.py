def positions(n):
    pos = ([1, 2, 3, 4] * ((n + 3) // 4))[:n]
    for _ in range(100):
        random.shuffle(pos)
        if all(not (pos[i] == pos[i + 1] == pos[i + 2]) for i in range(n - 2)):
            break
    return pos


used = set()


def fresh(lo, hi, ns=""):
    """A random answer in [lo, hi] not used before in the same namespace (part / rule)."""
    pool = [x for x in range(lo, hi + 1) if (ns, x) not in used]
    a = random.choice(pool)
    used.add((ns, a))
    return a


