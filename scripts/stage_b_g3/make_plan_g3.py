def deal(items, per_test, key=lambda x: x):
    """Spread a list over 8 tests, round robin after a shuffle, so no test gets two of a kind back to back."""
    items = items[:]
    random.shuffle(items)
    return [items[t::N][:per_test] if len(items) >= N * per_test else None for t in range(N)]


