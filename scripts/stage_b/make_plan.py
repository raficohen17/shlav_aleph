def balanced_positions(n):
    pos = [1,2,3,4] * ((n + 3)//4)
    pos = pos[:n]; random.shuffle(pos)
    for _ in range(50):  # avoid 3 in a row
        if all(not (pos[i]==pos[i+1]==pos[i+2]) for i in range(len(pos)-2)): break
        random.shuffle(pos)
    return pos

used_answers = {187, 170, 107, 14, 28}  # reserved: answers/numbers from the source tests
def small_products(lo, hi, maxf=12):
    return sorted({x*y for x in range(2, maxf+1) for y in range(2, maxf+1) if lo <= x*y <= hi})

