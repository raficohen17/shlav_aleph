plan = {t: {} for t in range(1, N_TESTS+1)}
for part, (title, k, subs) in CATALOG.items():
    ids = [s[0] for s in subs]
    # round-robin with a per-part stride so each test gets a different mix and totals stay balanced
    seq = []
    while len(seq) < k * N_TESTS:
        block = ids[:]; random.shuffle(block); seq += block
    for t in range(1, N_TESTS+1):
        chosen = []
        for sid in seq:
            if len(chosen) == k: break
            if sid not in chosen and counts[(part, sid)] <= min(counts[(part, x)] for x in ids):
                chosen.append(sid); counts[(part, sid)] += 1
        while len(chosen) < k:  # fill if the balancing rule left gaps
            sid = min(ids, key=lambda x: (counts[(part, x)], random.random()))
            if sid not in chosen: chosen.append(sid); counts[(part, sid)] += 1
        random.shuffle(chosen)
        pos = balanced_positions(k)
        items = []
        for i, sid in enumerate(chosen):
            sub = next(s for s in subs if s[0] == sid)
            seed = ""
            if part == 1: seed = "תחום: " + ANALOGY_DOMAINS[(t*3 + i*5) % len(ANALOGY_DOMAINS)]
            elif part == 2: seed = "נושא: " + SENT_THEMES[(t*2 + i*3) % len(SENT_THEMES)]
