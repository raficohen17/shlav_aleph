def fresh_answer(sid, lo, hi):
    pool = CANDIDATES.get(sid) or list(range(lo, hi + 1))
    random.shuffle(pool)
    for a in pool:
        if a not in used_answers:
            used_answers.add(a); return a
    return random.choice(pool)  # pool exhausted: reuse (still a valid answer for the type)

